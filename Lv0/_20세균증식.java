package Lv0;

public class _20세균증식 {

    /**
     *
     */
    public static void main(String[] args) {
       int n = 2;
       int k = 10;

       int answer = 7;

        /**
         *
         */
        for (int i = 1; i <= k; i++) {
            answer = answer * n;
        }

        System.out.println(answer);





    }




}